"""Generate antialiased native PlayStation face-button masks; Pillow required."""
from pathlib import Path
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parent
arrays=[]
for n in (11,14):
    for kind in ('cross','circle','square','triangle'):
        scale=8;im=Image.new('L',(n*scale,n*scale));d=ImageDraw.Draw(im)
        lo=1.5*scale;hi=(n-1.5)*scale;c=n*scale/2;w=round(1.5*scale)
        if kind=='circle':d.ellipse((lo,lo,hi,hi),outline=255,width=w)
        elif kind=='square':d.rectangle((lo,lo,hi,hi),outline=255,width=w)
        elif kind=='triangle':d.line([(c,lo),(hi,hi),(lo,hi),(c,lo)],fill=255,width=w,joint='curve')
        else:
            d.line((lo,lo,hi,hi),fill=255,width=w);d.line((hi,lo,lo,hi),fill=255,width=w)
        im=im.resize((n,n),Image.Resampling.LANCZOS)
        arrays.append('static const unsigned char button_%s_%d[%d]={%s};'%(kind,n,n*n,','.join(map(str,im.tobytes()))))
(root/'buttons.h').write_text('/* Generated by make_buttons.py. */\n'+'\n'.join(arrays)+'\n')
